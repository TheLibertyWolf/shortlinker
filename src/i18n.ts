export function translate(locale: Locale, value: string): string {
  return locale === "fr" ? french[value] ?? value : value;
}

export function localizeHtml(locale: Locale, html: string): string {
  if (locale !== "fr") return html;
  const textNodes = html.replace(/>([^<>]+)</g, (full, text: string) => {
    const key = text.trim();
    const translated = french[key];
    if (!translated) return full;
    const leading = text.slice(0, text.length - text.trimStart().length);
    const trailing = text.slice(text.trimEnd().length);
    return `>${leading}${translated}${trailing}<`;
  });
  return textNodes.replace(/(placeholder|aria-label|title)="([^"]+)"/g, (full, attribute: string, value: string) => {
    const translated = french[value];
    return translated ? `${attribute}="${translated}"` : full;
  });
}

export function localeTag(locale: Locale): string {
  return locale === "fr" ? "fr-FR" : "en-GB";
}
